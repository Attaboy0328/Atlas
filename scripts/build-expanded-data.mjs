#!/usr/bin/env node
/**
 * Build generated/foods-expanded-bulk.js from data/cn expanded food JSON sources.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { readCnJson, root } from "./lib/food-catalog.mjs";

const genDir = path.join(root, "generated");

const CATEGORY_MAP = {
  CAT_OFFICIAL: "食药物质",
  CAT_GRAIN: "谷物",
  CAT_DRINK: "饮品",
  CAT_TEA: "茶饮",
  CAT_VEG: "蔬菜",
  CAT_WILD: "野菜",
  CAT_FUNGI: "菌菇",
  CAT_FRUIT: "水果",
  CAT_PROTEIN: "肉蛋奶",
  CAT_SEA: "水产",
  CAT_CONDIMENT: "调料",
  CAT_PICKLE: "腌菜",
  CAT_TONIC: "滋补食材",
  CAT_NUT: "坚果种子",
  CAT_BEAN: "豆类",
  CAT_BEAN_PRODUCT: "豆制品",
  CAT_STARCH: "薯类",
  CAT_FERMENTED: "发酵食品"
};

function buildFood(id, name, nature, category, aliases, effects, regions, extra = {}) {
  return {
    id,
    name,
    en: aliases.find((alias) => /[a-z]/i.test(alias)) || name,
    jp: "",
    kr: "",
    aliases,
    effects,
    regions,
    category,
    nature,
    flavor: "未标注",
    meridians: [],
    summary: extra.summary || `${name}是常见${category}。传统食养中常见关键词为“${effects.join("、")}”，实际影响更取决于份量、加工方式和个人耐受。`,
    benefits: extra.benefits || [`传统食养常见关键词：${effects.join("、")}`, "日常营养价值需结合品种、份量与烹调方式评估"],
    caution: extra.caution || "请结合份量、加工方式与个人耐受综合判断；传统食性不替代现代医学结论。",
    cautionTags: extra.cautionTags || [],
    suitableFor: extra.suitableFor || [],
    avoidFor: extra.avoidFor || [],
    contraindications: extra.contraindications || [],
    officialFoodMedicine: Boolean(extra.officialFoodMedicine),
    officialBatch: extra.officialBatch || "",
    confidence: extra.confidence || "常见食材；传统属性待持续复核",
    teaClass: extra.teaClass || "",
    teaNote: extra.teaNote || "",
    searchTerms: extra.searchTerms || [],
    alone: extra.alone || "",
    timing: extra.timing || "",
    pair: extra.pair || "",
    qiTerms: extra.qiTerms || [],
    qiTermNote: extra.qiTermNote || "",
    varietyNote: extra.varietyNote || "",
    faCategory: extra.faCategory || "",
    faNote: extra.faNote || "",
    regulatoryNote: extra.regulatoryNote || "",
    sources: extra.sources || [],
    safetyNote: extra.safetyNote || ""
  };
}

function mapRegionalEntry(item) {
  const category = CATEGORY_MAP[item.category] || item.category;
  return buildFood(
    item.id,
    item.name,
    item.nature,
    category,
    item.aliases,
    item.effects,
    item.regions,
    item.extra || {}
  );
}

function mapOfficialBulk(item) {
  return buildFood(
    item.id,
    item.name,
    item.nature,
    CATEGORY_MAP.CAT_OFFICIAL,
    [item.name],
    item.effects,
    ["CN"],
    {
      officialFoodMedicine: true,
      officialBatch: item.officialBatch || "2025",
      confidence: item.confidence || "药食同源目录补回条目"
    }
  );
}

function mapExtraBulk(item) {
  const category = CATEGORY_MAP[item.category] || CATEGORY_MAP.CAT_TONIC;
  return buildFood(
    item.id,
    item.name,
    item.nature,
    category,
    [item.name],
    item.effects || ["日常食养"],
    item.regions || ["CN"],
    {
      confidence: item.confidence || "中国地方食材与常见食物扩充条目"
    }
  );
}

const regional = readCnJson("foods-regional-push.json", []);
const official = readCnJson("foods-official-bulk.json", []);
const extra = readCnJson("foods-extra-bulk.json", []);
const tail = readCnJson("foods-search-supplement.json", []);

const bulk = [
  ...regional.map(mapRegionalEntry),
  ...official.map(mapOfficialBulk),
  ...extra.map(mapExtraBulk),
  ...tail.map(mapRegionalEntry)
];

fs.mkdirSync(genDir, { recursive: true });
fs.writeFileSync(
  path.join(genDir, "foods-expanded-bulk.js"),
  `/** Auto-generated by scripts/build-expanded-data.mjs — do not edit */\nconst EXPANDED_FOODS_BULK = ${JSON.stringify(bulk, null, 2)};\n`,
  "utf8"
);

console.log(`Expanded bulk foods: ${bulk.length} (regional ${regional.length}, official ${official.length}, extra ${extra.length}, tail ${tail.length})`);
console.log("Output: generated/foods-expanded-bulk.js");
