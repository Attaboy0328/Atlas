import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
let version = "dev";

try {
  version = execSync("git rev-parse --short HEAD", { cwd: root, encoding: "utf8" }).trim();
} catch {
  // Non-git environments fall back to dev.
}

const outDir = path.join(root, "generated");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  path.join(outDir, "app-version.js"),
  `/** Auto-generated by scripts/write-app-version.mjs — do not edit */\nconst APP_VERSION = ${JSON.stringify(version)};\n`,
  "utf8"
);

console.log(`[write-app-version] ${version}`);
