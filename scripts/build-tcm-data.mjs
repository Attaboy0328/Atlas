#!/usr/bin/env node
/**
 * Build TCM herb bundle and classic diet recipes from data/tcm/*.json
 * Single source: herbs-chp2025.json
 * Run: node scripts/build-tcm-data.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const tcmDir = path.join(root, "data", "tcm");
const cnDir = path.join(root, "data", "cn");
const genDir = path.join(root, "generated");

function readJson(name, fallback = []) {
  const file = path.join(tcmDir, name);
  if (!fs.existsSync(file)) return fallback;
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function readCnJson(name, fallback = []) {
  const file = path.join(cnDir, name);
  if (!fs.existsSync(file)) return fallback;
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function writeJs(outPath, constName, data) {
  fs.writeFileSync(
    outPath,
    `/** Auto-generated by scripts/build-tcm-data.mjs — do not edit */\nconst ${constName} = ${JSON.stringify(data, null, 2)};\n`,
    "utf8"
  );
}

function loadCatalogIds() {
  const ids = new Set();
  const expanded = fs.readFileSync(path.join(root, "foods-expanded.js"), "utf8");
  const fRe = /f\(\s*["']([^"']+)["']/g;
  let m;
  while ((m = fRe.exec(expanded))) ids.add(m[1]);
  for (const file of ["pairing-aliases.json", "regional-foods.json", "expansion-batch4.json", "foods-ingredients.json"]) {
    const cnPath = path.join(cnDir, file);
    if (!fs.existsSync(cnPath)) continue;
    JSON.parse(fs.readFileSync(cnPath, "utf8")).forEach((food) => ids.add(food.id));
  }
  readJson("herbs-chp2025.json", []).forEach((herb) => ids.add(herb.id));
  const runtimeMatch = fs.readFileSync(path.join(root, "app.js"), "utf8").match(/const RUNTIME_FOOD_EXPANSION = \[([\s\S]*?)\n\];/);
  if (runtimeMatch) {
    const idRe = /id:\s*["']([^"']+)["']/g;
    while ((m = idRe.exec(runtimeMatch[1]))) ids.add(m[1]);
  }
  return ids;
}

function normalizeHerb(herb) {
  return {
    ...herb,
    pharmacopoeiaEdition: herb.pharmacopoeiaEdition || "2025",
    itemKind: herb.itemKind || (herb.officialFoodMedicine ? "food-medicine" : "tcm-herb"),
    usageScope: herb.usageScope || (herb.officialFoodMedicine ? "dietary-therapy" : "reference-only"),
    category: herb.category || (herb.itemKind === "food-medicine" ? "食药物质" : "中药材"),
    regions: herb.regions || ["CN"]
  };
}

const rawHerbs = readJson("herbs-chp2025.json", []);
const idSet = new Set();
const nameSet = new Set();
const herbs = [];

rawHerbs.map(normalizeHerb).forEach((herb) => {
  if (idSet.has(herb.id)) {
    console.warn(`Skip duplicate herb id "${herb.id}" (${herb.name})`);
    return;
  }
  if (nameSet.has(herb.name)) {
    console.warn(`Skip duplicate herb name "${herb.name}"`);
    return;
  }
  idSet.add(herb.id);
  nameSet.add(herb.name);
  herbs.push(herb);
});

herbs.sort((a, b) => a.name.localeCompare(b.name, "zh-CN"));

function collectPublishedRecipeNames() {
  const app = fs.readFileSync(path.join(root, "app.js"), "utf8");
  const names = new Set();
  const recipeRe = /recipe\(\s*["'][^"']+["']\s*,\s*["']([^"']+)["']/g;
  let m;
  while ((m = recipeRe.exec(app))) names.add(m[1]);
  return names;
}

const catalog = loadCatalogIds();
const publishedNames = collectPublishedRecipeNames();
const rawClassic = readJson("classic-diet-recipes.json");
const classicRecipes = rawClassic
  .map((item) => {
    const isClassicVariant = /（经典）$/.test(item.name);
    if (publishedNames.has(item.name) && !isClassicVariant) {
      console.warn(`Skip classic recipe "${item.name}": duplicate of hand-crafted recipe`);
      return null;
    }
    const foodIds = (item.foodIds || []).filter((id) => catalog.has(id));
    if (foodIds.length < 1) {
      console.warn(`Skip classic recipe "${item.name}": no valid foodIds`);
      return null;
    }
    return {
      ...item,
      foodIds,
      draft: false,
      classicTier: 1,
      sources: item.sources || []
    };
  })
  .filter(Boolean);

fs.mkdirSync(genDir, { recursive: true });
writeJs(path.join(genDir, "tcm-herbs-bundle.js"), "TCM_HERBS_CORE", herbs);
writeJs(path.join(genDir, "classic-diet-recipes.js"), "CLASSIC_DIET_RECIPES", classicRecipes);

const publicDir = path.join(root, "public", "data", "tcm");
fs.mkdirSync(publicDir, { recursive: true });
fs.writeFileSync(path.join(publicDir, "herbs-chp2025.json"), JSON.stringify(herbs, null, 2));
fs.writeFileSync(path.join(publicDir, "classic-diet-recipes.json"), JSON.stringify(classicRecipes, null, 2));

console.log(`TCM herbs: ${herbs.length} (from herbs-chp2025.json)`);
console.log(`Classic diet recipes published: ${classicRecipes.length} / ${rawClassic.length}`);
console.log(`Output: generated/tcm-herbs-bundle.js, generated/classic-diet-recipes.js`);
