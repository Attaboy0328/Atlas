const PLACEHOLDER_SOURCE = "地域食疗整理";

export function resolveClassicSources(food) {
  if (Array.isArray(food.sources) && food.sources.length) {
    return food.sources.filter((s) => s?.title && s.title !== PLACEHOLDER_SOURCE);
  }
  const byId = BY_ID[food.id];
  if (byId?.length) return byId;
  const byName = BY_NAME[food.name];
  if (byName?.length) return byName;
  for (const alias of food.aliases || []) {
    if (BY_NAME[alias]?.length) return BY_NAME[alias];
  }
  const category = CATEGORY_FALLBACK[food.category];
  if (category?.length) return category;
  const nature = NATURE_FALLBACK[food.nature] || NATURE_FALLBACK.平;
  return nature;
}

export function enrichFoodClassicSources(food) {
  const sources = resolveClassicSources(food);
  if (!sources.length) return food;
  return { ...food, sources };
}

export function buildClassicSourcesBundle() {
  return { byId: BY_ID, byName: BY_NAME, categoryFallback: CATEGORY_FALLBACK, natureFallback: NATURE_FALLBACK };
}
